#!/usr/bin/env node
/**
 * Bundle the MyST plugin into a single self-contained ESM file.
 *
 * MyST loads a plugin from a local path or a URL and gives it no module
 * resolution of its own, so the artifact must carry everything it needs. Only
 * the directive is bundled: the CLI, the exporter and the validator use Node
 * built-ins and have no business inside a file a browser-facing build may
 * fetch.
 */
import { build } from "esbuild";
import { mkdirSync } from "node:fs";

mkdirSync("dist", { recursive: true });

const result = await build({
  entryPoints: ["src/plugin.ts"],
  outfile: "dist/oratlas-myst.mjs",
  bundle: true,
  format: "esm",
  // MyST loads plugins inside its Node CLI, so Node built-ins stay external
  // and are resolved at load time rather than bundled.
  platform: "node",
  target: ["node20"],
  legalComments: "inline",
  metafile: true,
  banner: {
    js: "// @neuronautix/myst — MyST plugin bundle. Generated by scripts/bundle-plugin.mjs; do not edit.",
  },
});

const outputs = Object.entries(result.metafile.outputs);
for (const [file, meta] of outputs) {
  console.log(`bundled ${file} (${(meta.bytes / 1024).toFixed(1)} kB)`);
}
